import esbuild from "esbuild";
import { builtinModules } from "node:module";
import "./scripts/gen-mac-files.mjs";

const banner = `/*
Habit Grid - generated by esbuild from src/. Edit the files in src/, not this file.
https://github.com/yeongseo1225/obsidian-habit-grid
*/
`;
const prod = process.argv[2] === "production";

const ctx = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.js"],
  bundle: true,
  external: ["obsidian", "electron", "@codemirror/*", "@lezer/*", ...builtinModules],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  charset: "utf8",
  outfile: "main.js",
});

if (prod) {
  await ctx.rebuild();
  process.exit(0);
} else {
  await ctx.watch();
}
