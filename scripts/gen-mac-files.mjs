// Copies the Mac sync scripts into src/macSyncFiles.js so the plugin can write them into the vault.
// Run automatically by esbuild.config.mjs. The scripts/ folder is the source of truth.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const names = ["habit-log-sync.sh", "install-mac-sync.sh"];
const files = Object.fromEntries(names.map((n) => [n, readFileSync(join(root, "scripts", n), "utf8")]));
const out = "// Generated by scripts/gen-mac-files.mjs from scripts/*.sh. Do not edit by hand.\nexport const MAC_SYNC_FILES = " + JSON.stringify(files, null, 2) + ";\n";
writeFileSync(join(root, "src", "macSyncFiles.js"), out);
